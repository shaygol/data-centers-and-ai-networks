"""Generate public/js/puzzle.js (the puzzle data) from the cluster model.
Run from exercises/ex3/site:  python3 tools/gen_puzzle.py > public/js/puzzle.js
The model below is the same as the one that defined the shared version of the exercise.
NOTE: the answer key is inside the generated file. That is fine: the exercise is ungraded."""
import json, io, sys, contextlib, runpy, os

SRC = os.environ.get("MH_GEN_SEED", "/mnt/project-files/unit3/miswire-hunt/gen_seed.py")
sys.argv = ["gen_seed.py", "unused"]
buf = io.StringIO()
with contextlib.redirect_stdout(buf), contextlib.redirect_stderr(io.StringIO()):
    g = runpy.run_path(SRC)

views = {}
for sw, port, exp, disc, peer, phy, err in g["views"]:
    views.setdefault(sw, []).append([port, exp, disc, peer, phy, err])
truth = {}
for p, (labels, fid) in g["truth"].items():
    sw, port = p.split(":")
    truth[sw + ":" + port] = {"a": labels, "f": fid}
faults = [{"id": a, "title": b, "text": c, "ref": d} for a, b, c, d in g["faults"]]
data = {"views": views, "truth": truth, "faults": faults, "rc": {"q1": "crash", "q2": "oneway"}}
print("// Generated by tools/gen_puzzle.py. Contains the answer key (the exercise is ungraded).")
print("window.MH_PUZZLE = " + json.dumps(data, separators=(",", ":")) + ";")
